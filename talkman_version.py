def version_label():
    return f'{VERSION} · 构建 {BUILD} · {RELEASE_DATE}'


def windows_resource():
    numbers = tuple(map(int, VERSION.split('.'))) + (BUILD,)
    values = [('CompanyName', 'Cololight'), ('FileDescription', PRODUCT_NAME),
              ('FileVersion', '.'.join(map(str, numbers))), ('ProductName', PRODUCT_NAME),
              ('ProductVersion', VERSION), ('OriginalFilename', 'TalkMan.exe')]
    strings = ','.join(f'StringStruct({k!r},{v!r})' for k, v in values)
    return (f'VSVersionInfo(ffi=FixedFileInfo(filevers={numbers!r},prodvers={numbers!r},'
            'mask=0x3f,flags=0,OS=0x40004,fileType=1,subtype=0,date=(0,0)),'
            f"kids=[StringFileInfo([StringTable('040904B0',[{strings}])]),"
            'VarFileInfo([VarStruct(\'Translation\',[1033,1200])])])')


if __name__ == '__main__' and len(sys.argv) == 3 and sys.argv[1] == '--windows-resource':
    Path(sys.argv[2]).write_text(windows_resource(), encoding='utf-8')
